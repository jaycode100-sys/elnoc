# ELNOC_HOSTING.md — set up permanent free hosting. Run from the repo root.
# Zero cost: Cloudflare free plan + Supabase free tier + this PC.
# Requires ONE manual step (browser login) — everything else this script does.
param(
  [string]$Hostname = "noc.cedarviewng.com",
  [string]$TunnelName = "elnoc",
  [string]$ServiceUrl = "http://127.0.0.1:8000"
)

$ErrorActionPreference = "Stop"
$cf = Join-Path $PSScriptRoot "..\tools\cloudflared.exe"
if (-not (Test-Path $cf)) { Write-Host "cloudflared.exe missing - download it first."; exit 1 }

# ---- Step 0: ELNOC must be serving locally first
try {
  $h = Invoke-WebRequest "http://127.0.0.1:8000/health" -TimeoutSec 5
  Write-Host "[ok] ELNOC is up on 127.0.0.1:8000"
} catch {
  Write-Host "[!] ELNOC is not answering on 8000. Start tools\run_server.bat first, then re-run."
  exit 1
}

# ---- Step 1: one manual browser login (free, no card)
$certDir = Join-Path $env:USERPROFILE ".cloudflared"
$cert = Join-Path $certDir "cert.pem"
if (-not (Test-Path $cert)) {
  Write-Host ""
  Write-Host ">>> ONE MANUAL STEP: a browser window will open. Pick your domain"
  Write-Host ">>> (cedarviewng.com), click Authorize. That is the only manual step."
  Write-Host ""
  & $cf tunnel login
  if (-not (Test-Path $cert)) { Write-Host "[x] login did not complete."; exit 1 }
}
Write-Host "[ok] authenticated"

# ---- Step 2: create the named tunnel (idempotent)
$tun = & $cf tunnel list --output json 2>$null | ConvertFrom-Json
$existing = $tun | Where-Object { $_.name -eq $TunnelName }
if ($existing) {
  $uuid = $existing.id
  Write-Host "[ok] tunnel '$TunnelName' already exists ($uuid)"
} else {
  $created = & $cf tunnel create $TunnelName 2>&1
  $uuid = ([regex]::Match(($created -join "`n"), "([0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12})")).Groups[1].Value
  if (-not $uuid) { Write-Host "[x] could not create tunnel: $created"; exit 1 }
  Write-Host "[ok] tunnel '$TunnelName' created ($uuid)"
}

# ---- Step 3: write config.yml (public hostname -> local server)
$cfgDir = Join-Path $certDir "config.yml"
@"
# ELNOC - generated by tools/setup_tunnel.ps1
tunnel: $uuid
credentials-file: $certDir\$uuid.json
ingress:
  - hostname: $Hostname
    service: $ServiceUrl
  - service: http_status:404
"@ | Set-Content -Path $cfgDir -Encoding utf8
Write-Host "[ok] wrote $cfgDir"

# ---- Step 4: point the DNS name at the tunnel
& $cf tunnel route dns $TunnelName $Hostname 2>&1 | Out-Null
Write-Host "[ok] routed $Hostname -> tunnel"

# ---- Step 5: run it as a Windows service (starts at boot, survives reboots)
$svc = Get-Service -Name "cloudflared" -ErrorAction SilentlyContinue
if (-not $svc) {
  & $cf service install 2>&1 | Out-Null
  Write-Host "[ok] cloudflared installed as a Windows service"
} else {
  Write-Host "[ok] cloudflared service already present"
}

Write-Host ""
Write-Host "=== DONE. Two things left, both 30 seconds:"
Write-Host "1) In .env set  ELNOC_BASE_URL=https://$Hostname   then restart the server."
Write-Host "2) Open      https://$Hostname/health  -> should print ELNOC ok."
Write-Host "   Then      https://$Hostname/        -> the landing page."