# ELNOC_HOSTING.md - permanent free hosting. Run from the repo root.
# Zero cost: Cloudflare free tunnel + Supabase free tier + this PC.
param(
  [string]$Hostname = "noc.cedarviewng.com",
  [string]$TunnelName = "elnoc",
  [string]$ServiceUrl = "http://127.0.0.1:8000"
)

# NOTE: cloudflared writes normal progress to STDERR. With
# ErrorActionPreference='Stop' PowerShell turns those lines into terminating
# errors, which is what broke the first run. Native calls are therefore made
# with the preference relaxed.
$ErrorActionPreference = "Continue"
$cf = Join-Path $PSScriptRoot "cloudflared.exe"
if (-not (Test-Path $cf)) { Write-Host "cloudflared.exe missing."; exit 1 }

function Invoke-Cf { param([string[]]$Args)
  & $cf @Args 2>&1 | ForEach-Object { Write-Host "   $_" }
}

# ---- 0. ELNOC must be serving locally
# Invoke-WebRequest misbehaves in non-interactive shells, so use curl.exe
# (present on Windows 10+) and fall back to a TCP probe.
$up = $false
try {
  $r = & curl.exe -s -m 5 "http://127.0.0.1:8000/health" 2>$null
  if ($r -and $r -match "ELNOC") { $up = $true }
} catch { }
if (-not $up) {
  $tcp = New-Object System.Net.Sockets.TcpClient
  try { $tcp.Connect("127.0.0.1", 8000); $up = $true } catch { } finally { $tcp.Close() }
}
if ($up) { Write-Host "[ok] ELNOC is up on 127.0.0.1:8000" }
else {
  Write-Host "[!] ELNOC is not answering on 8000. Start tools\run_server.bat first."
  exit 1
}

# ---- 1. login (one manual browser step)
$certDir = Join-Path $env:USERPROFILE ".cloudflared"
if (-not (Test-Path (Join-Path $certDir "cert.pem"))) {
  Write-Host ""
  Write-Host ">>> ONE MANUAL STEP: a browser opens. Pick your domain, Authorize."
  Write-Host ""
  Invoke-Cf @("tunnel", "login")
}
Write-Host "[ok] authenticated"

# ---- 2. create tunnel (idempotent)
$tun = & $cf tunnel list --output json 2>$null | ConvertFrom-Json
$existing = $tun | Where-Object { $_.name -eq $TunnelName }
if ($existing) {
  $uuid = $existing.id
  Write-Host "[ok] tunnel '$TunnelName' exists ($uuid)"
} else {
  $out = (& $cf tunnel create $TunnelName 2>&1) -join "`n"
  $uuid = ([regex]::Match($out, "([0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12})")).Groups[1].Value
  if (-not $uuid) { Write-Host "[x] create failed: $out"; exit 1 }
  Write-Host "[ok] tunnel '$TunnelName' created ($uuid)"
}

# ---- 3. config.yml
@"
# ELNOC - generated by tools/setup_tunnel.ps1
# Catch-all sends any hostname pointed at this tunnel to ELNOC, because the
# public hostname may be a domain you control, a quick tunnel, or a free DNS
# subdomain. Without this, unknown hostnames get a 404.
tunnel: $uuid
credentials-file: $certDir\$uuid.json
ingress:
  - hostname: $Hostname
    service: $ServiceUrl
  - service: $ServiceUrl
"@ | Set-Content -Path (Join-Path $certDir "config.yml") -Encoding utf8
Write-Host "[ok] wrote $certDir\config.yml"

# ---- 4. DNS. cloudflared can only write DNS where it is authoritative.
# If the domain is NOT on Cloudflare nameservers it will report success into a
# zone that nobody queries. So we check, and otherwise print the CNAME to add
# at the real DNS host.
$domain = ($Hostname -split '\.')[-2..-1] -join '.'
$ns = Resolve-DnsName -Name $domain -Type NS -ErrorAction SilentlyContinue
$onCloudflare = @($ns | Where-Object { $_.NameHost -like "*cloudflare*" }).Count -gt 0
Invoke-Cf @("tunnel", "route", "dns", $TunnelName, $Hostname)
if (-not $onCloudflare) {
  Write-Host ""
  Write-Host "[!] $domain is NOT on Cloudflare nameservers."
  Write-Host "    cloudflared could not publish the record where the internet looks."
  Write-Host "    Add this CNAME at whichever panel manages your DNS:"
  Write-Host ""
  Write-Host "        $Hostname  CNAME  $uuid.cfargotunnel.com"
  Write-Host ""
  Write-Host "    (Or move the domain to Cloudflare nameservers and re-run.)"
}

# ---- 5. run the tunnel. Service needs Administrator; otherwise use a logon task.
$isAdmin = ([Security.Principal.WindowsPrincipal] `
            [Security.Principal.WindowsIdentity]::GetCurrent()
           ).IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)

$svc = Get-Service -Name "cloudflared" -ErrorAction SilentlyContinue
if ($svc) {
  Write-Host "[ok] cloudflared Windows service present"
} elseif ($isAdmin) {
  Invoke-Cf @("service", "install")
  Write-Host "[ok] installed as a Windows service (starts at boot)"
} else {
  # No admin: a logon task keeps it alive across restarts of the session.
  $task = "ELNOC-Tunnel"
  $act = "`"$cf`" tunnel run elnoc"
  schtasks /create /tn $task /tr $act /sc onlogon /f 2>&1 | Out-Null
  if ($LASTEXITCODE -eq 0) {
    Write-Host "[ok] created logon task '$task' (starts when you sign in)"
  } else {
    Write-Host "[!] could not create the logon task here (needs your own session)."
    Write-Host "    Either re-run this script AS ADMINISTRATOR (best: installs the"
    Write-Host "    Windows service), or add the task by hand in Task Scheduler:"
    Write-Host "      Trigger: At log on"
    Write-Host "      Action :  $cf  tunnel run elnoc"
    Write-Host "      Start in: $PSScriptRoot\.."
  }
}

Write-Host ""
Write-Host "=== DONE. Two quick steps left:"
Write-Host "1) .env:  ELNOC_BASE_URL=https://$Hostname    then restart the server."
Write-Host "2) Check https://$Hostname/health  ->  should print ELNOC ok."