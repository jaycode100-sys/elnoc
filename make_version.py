"""Generate a PyInstaller --version-file from AppVersion in build_elnoc_installer.iss.

Keeps the exe's File Properties (Details tab) in sync with the installer
version automatically. Called by build_elnoc_onefile.ps1 before PyInstaller.

Usage: py make_version.py   -> writes version_elnoc.txt
"""
import re
from pathlib import Path

root = Path(__file__).parent
iss = (root / "build_elnoc_installer.iss").read_text(encoding="utf-8")

m = re.search(r"^AppVersion=(\S+)", iss, re.MULTILINE)
version = m.group(1) if m else "0.0.0"
print(f"inno setup AppVersion found: {version}")

nums = [int(x) for x in version.split(".")[:4]]
while len(nums) < 4:
    nums.append(0)
versions = tuple(nums)

TEMPLATE = """# -*- coding: utf-8 -*-
# Auto-generated by make_version.py -- do not edit by hand.
VSVersionInfo(
  ffi=FixedFileInfo(
    filevers=VERSIONS,
    prodvers=VERSIONS,
    mask=0x3F,
    flags=0x0,
    OS=0x40004,
    fileType=0x1,
    subtype=0x0,
    date=(0, 0)
  ),
  kids=[
    StringFileInfo([
      StringTable('040904B0', [
        StringStruct('CompanyName', 'ELNOC'),
        StringStruct('FileDescription', 'ELNOC Network Operations Center'),
        StringStruct('FileVersion', 'V'),
        StringStruct('InternalName', 'ELNOC'),
        StringStruct('LegalCopyright', '(c) ELNOC'),
        StringStruct('OriginalFilename', 'ELNOC.exe'),
        StringStruct('ProductName', 'ELNOC'),
        StringStruct('ProductVersion', 'V')
      ])
    ]),
    VarFileInfo([VarStruct('Translation', [1033, 1200])])
  ]
)
"""

content = TEMPLATE.replace("VERSIONS", "(%s)" % ", ".join(str(p) for p in versions))
content = content.replace("'V'", repr(version))

(root / "version_elnoc.txt").write_text(content, encoding="utf-8")
print(f"wrote version_elnoc.txt  (filevers={versions})")
